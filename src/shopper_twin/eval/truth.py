"""The true store, rebuilt from a world's answer key. Only evaluation code may use this module.

Because the store is simulated, it can be run again from any day with different prices. From that day on the
simulator uses common random numbers (see keyed_random.py): every random draw depends only on what it is for
(day, shopper, category, product), so two runs that differ only in their prices differ only where the prices
mattered. Their difference is the true effect of the change, which a real retailer can never observe.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, fields
from pathlib import Path

import numpy as np
import pandas as pd

from ..world.config import Rules, WorldConfig
from ..world.generate import build_world
from ..world.simulate import PURCHASE, SimState


def config_from_answer_key(world_dir: str | Path) -> WorldConfig:
    """The exact settings the world was generated with (they are only stored in the answer key)."""
    manifest = json.loads((Path(world_dir) / "answer_key" / "manifest.json").read_text(encoding="utf-8"))
    cfg = dict(manifest["config"])
    rules = {f.name: cfg["rules"][f.name] for f in fields(Rules) if f.name in cfg["rules"]}
    rules["weekday_visit_mult"] = tuple(rules["weekday_visit_mult"])
    cfg["rules"] = Rules(**rules)
    return WorldConfig(**{f.name: cfg[f.name] for f in fields(WorldConfig) if f.name in cfg})


class TrueStore:
    """The simulated store behind a generated world, ready to be re-run with other prices."""

    def __init__(self, world_dir: str | Path):
        self.path = Path(world_dir)
        self.cfg = config_from_answer_key(self.path)
        self.catalog, self.population, self.prices, self.sim = build_world(self.cfg)
        public = pd.read_parquet(self.path / "public" / "price_history.parquet")
        planned = self.prices.price[public.product_id.to_numpy(), public.week.to_numpy()]
        if not np.allclose(planned, public.price.to_numpy(), atol=1e-6):
            raise ValueError(f"{self.path} was generated by a different version of the world generator; "
                             f"regenerate it with scripts/generate_world.py")
        self._states: dict[int, SimState] = {}

    def state_at(self, day: int) -> SimState:
        """The store on the morning of `day`, exactly as in the public data (a fresh copy each time)."""
        if day not in self._states:
            self._states[day] = self.sim.state_at(day)
        return self._states[day].copy()

    def purchases(self, first_day: int, last_day: int, plan=None, replicate: int = 0) -> pd.DataFrame:
        """Every purchase on days first_day..last_day when the store runs with `plan` (a PricePlan; None = the
        store's own plan). Replicates use different sets of common random numbers."""
        unavailable = None if plan is None else plan.unavailable
        parts = []
        for log in self.sim.run(prices=plan, unavailable=unavailable, state=self.state_at(first_day),
                                stop_day=last_day + 1, crn_from_day=first_day, replicate=replicate):
            buy = log.event_type == PURCHASE
            parts.append(pd.DataFrame({"shopper_id": log.shopper_id[buy], "product_id": log.product_id[buy],
                                       "quantity": log.quantity[buy].astype(np.int64),
                                       "price": log.price[buy].astype(np.float64), "day": log.day}))
        return pd.concat(parts, ignore_index=True)


@dataclass
class Outcome:
    """Units and revenue per product over a window, from one run of the true store."""

    units: np.ndarray  # [products]
    revenue: np.ndarray  # [products]
    shopper_units: pd.Series  # units per (shopper_id, product_id), for segment breakdowns

    @classmethod
    def from_purchases(cls, purchases: pd.DataFrame, n_products: int) -> "Outcome":
        p = purchases.product_id.to_numpy()
        q = purchases.quantity.to_numpy()
        return cls(units=np.bincount(p, weights=q, minlength=n_products),
                   revenue=np.bincount(p, weights=q * purchases.price.to_numpy(), minlength=n_products),
                   shopper_units=purchases.groupby(["shopper_id", "product_id"]).quantity.sum())


def true_effect(base: list[Outcome], new: list[Outcome], target: np.ndarray, in_categories: np.ndarray) -> dict:
    """% change in the changed products' units, their categories' units and revenue, per replicate and on
    average. `target` and `in_categories` are [products] masks."""
    out = {}
    for key, mask, what in (("target_units", target, "units"), ("category_units", in_categories, "units"),
                            ("category_revenue", in_categories, "revenue")):
        pct = np.array([100 * (getattr(n, what)[mask].sum() / getattr(b, what)[mask].sum() - 1)
                        for b, n in zip(base, new)])
        base_total = np.mean([getattr(b, what)[mask].sum() for b in base])
        new_total = np.mean([getattr(n, what)[mask].sum() for n in new])
        out[key] = {"base": float(base_total), "new": float(new_total),
                    "pct": float(100 * (new_total / base_total - 1)),
                    "replicates": pct.round(4).tolist(),
                    "se": float(pct.std(ddof=1) / np.sqrt(len(pct))) if len(pct) > 1 else None}
    return out
